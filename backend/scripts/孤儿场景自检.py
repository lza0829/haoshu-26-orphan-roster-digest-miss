def 重置库() -> None:
    try:
        db.库路径.unlink()
    except FileNotFoundError:
        pass
    seed.初始化库()


def 卫星数(表: str = "卫星_号卡属性") -> int:
    conn = 连接()
    try:
        return conn.execute(f"SELECT COUNT(*) AS c FROM {表}").fetchone()["c"]
    finally:
        conn.close()


def 贯验行数() -> int:
    conn = 连接()
