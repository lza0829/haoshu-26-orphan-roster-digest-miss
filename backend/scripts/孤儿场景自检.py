def 场景_覆盖戳分叉() -> None:
    重置库()
    print("\n[4] 夹具灌历史孤儿再切覆盖：架构「规」重跑必须扫出历史孤儿")
    r = 跑("孤儿-覆盖戳分叉")
    贯验步 = [x for x in r["步骤"] if x.get("动作") == "跑贯验"]
    断言(len(贯验步) == 2, "两次跑贯验（仅当前 / 当前+历史）")
    窄, 宽 = 贯验步
    # —— 仅当前跑次：历史漏网，结论通过，但戳必须诚实钉「仅当前」——
    断言(窄["是否通过"] is True, "仅当前口径：无当前孤儿，结论通过")
    断言(窄["历史孤儿数"] == 0 and 窄["当前孤儿数"] == 0, "仅当前戳下历史孤儿漏扫（件数=0）")
    断言(窄["覆盖戳"]["覆盖范围"] == "仅当前", "窄跑次戳范围=仅当前")
    断言(窄["覆盖戳"]["站规版本"].endswith(":仅当前"), "窄戳钉站规版本")
    窄跑次 = 窄["跑次号"]
    # —— 切回当前+历史重跑：架构「规」按现行站规重扫，历史必须现形 ——
    断言(宽["是否通过"] is False, "当前+历史重跑：历史孤儿现形，贯验失败")
    断言(宽["历史孤儿数"] >= 1, "历史孤儿被扫出（对照架构「戳」此处会继续漏网）")
    断言(宽["覆盖戳"]["覆盖范围"] == "当前+历史", "宽跑次钉新戳、范围=当前+历史")
    断言(宽["跑次号"] != 窄跑次, "每次贯验新开跑次、跑次号递增")
    # —— 旧戳只读核证：与现行站规分叉，禁止沿用 ——
    conn = 连接()
    try:
        旧证 = 孤戳.核证(conn, 跑次号=窄跑次)
        新证 = 孤戳.核证(conn)
    finally:
        conn.close()
    断言(not 旧证["核证通过"] and not 旧证["可否沿用结论"], "旧仅当前戳与现行分叉，核证失败、禁沿用")
    断言(any("分叉" in x for x in 旧证["分叉"]), "核证给出分叉原因")
    断言(新证["核证通过"] and 新证["覆盖范围"] == "当前+历史", "末次新戳核证通过")
    # —— 硬约束：不存在「结论已落而戳空」——
    断言(贯验行数() == 戳行数(), "贯验结论数与覆盖戳数 1:1，无空戳结论")


def 场景_清扫写闸() -> None:
    重置库()
    print("\n[5] 清扫写闸：无戳拒、分叉拒、互证后放行")
    r = 跑("孤儿-清扫写闸")
    清扫步 = [x for x in r["步骤"] if x.get("动作") == "清扫孤儿"]
    断言(len(清扫步) == 3, "三次清扫尝试")
    断言(清扫步[0]["结果"] == "拒绝", "无戳清扫被拒（禁止无戳改写正式孤儿处置）")
    断言(清扫步[1]["结果"] == "拒绝", "戳与现行站规分叉，清扫被拒")
    断言(清扫步[2]["结果"] == "成功" and 清扫步[2]["处置数"] >= 1, "互证一致后清扫成功")
    断言(处置行数() == 1, "正式孤儿处置留痕一单")
    断言(清扫步[2]["跑次号"] and 清扫步[2]["覆盖戳编号"], "处置单钉跑次号与戳编号")
    末贯 = [x for x in r["步骤"] if x.get("动作") == "跑贯验"][-1]
    断言(末贯["是否通过"] is True and 末贯["孤儿数"] == 0, "清扫后重贯验通过、零孤儿")
    # 无孤儿可扫：闸互证一致、处置数 0 的幂等空扫，不产生新处置单
    空 = 清扫.清扫孤儿()
    断言(空["结果"] == "成功" and 空["处置数"] == 0 and 处置行数() == 1, "零孤儿空扫幂等、不增处置单")
    # 真正的漂移：钉戳后再删枢纽制造新孤儿，件数与戳不符，必须拒扫
    重置库()
    跑("孤儿-当前")
    贯验.跑贯验()  # 钉戳：孤儿 1 件
    装载.装一批({
        "装载日": "2026-11-23",
        "批次编号": "批-漂移-第二孤儿",
        "枢纽": {"号卡": [{"业务键": "卡-漂移-二"}], "套餐": [], "客户": []},
        "链接": {"号卡套餐": [], "号卡客户": []},
        "卫星": {"号卡": [{"业务键": "卡-漂移-二", "属性": {"v": 1}}], "套餐": [], "客户": [], "订购": []},
    })
    装载.删除枢纽("号卡", "卡-漂移-二")
    漂 = 清扫.清扫孤儿()
    断言(漂["结果"] == "拒绝" and "不符" in 漂["说明"], "戳后数据漂移，未重钉戳前禁止清扫")


def 场景_半截回滚() -> None:
    重置库()
    print("\n[6] 半截写戳失败：结论已落而戳空——整票回滚")
    跑("孤儿-当前")
    贯前, 戳前 = 贯验行数(), 戳行数()
    贯验.故障_钉戳前炸 = True
    抛出 = False
    try:
        贯验.跑贯验()
    except RuntimeError as e:
        抛出 = "故障注入" in str(e)
    断言(抛出, "钉戳前故障向上抛出，未被吞掉")
    断言(贯验行数() == 贯前 and 戳行数() == 戳前, "结论与戳整票回滚，无半截落库")
    断言(not 贯验.故障_钉戳前炸, "故障旗标一次性消费")
    # 回滚后库仍自洽：重跑可正常钉戳
    补 = 贯验.跑贯验()
    断言(补["覆盖戳"]["孤儿件数"] == 1 and 戳行数() == 戳前 + 1, "回滚后重跑正常钉戳")

    print("\n[7] 半截清扫失败：处置整票回滚")
    # 当前库有 1 个当前孤儿且末次戳互证一致
    处前, 卫前 = 处置行数(), 卫星数()
    清扫.故障_清扫中炸 = True
    报 = 清扫.清扫孤儿()
    断言(报["结果"] == "失败", "清扫半截故障返回失败")
    断言(处置行数() == 处前 and 卫星数() == 卫前, "隔离/删除/处置单全部回滚，卫星行还在")
    成 = 清扫.清扫孤儿()
    断言(成["结果"] == "成功" and 卫星数() == 卫前 - 1, "故障后重扫清扫成功")


def 场景_并发改站规与贯验() -> None:
    重置库()
    print("\n[8] 并发：扫贯验与改站规交错——不得漏网标通过")
    跑("孤儿-历史")  # 库内有仅历史孤儿；重置后默认站规=当前+历史
    # 先把站规切到仅当前并贯验，得到一个通过的窄戳（历史漏网但戳诚实）
    断言(站规.改孤儿覆盖("仅当前")["结果"] == "成功", "切仅当前")
    窄 = 贯验.跑贯验()
    断言(窄["是否通过"] is True and 窄["覆盖戳"]["覆盖范围"] == "仅当前", "窄跑次通过、戳=仅当前")

    就绪 = threading.Event()
    战果: dict = {}

    def 贯验线程() -> None:
        就绪.wait()
        try:
            战果["贯验"] = 贯验.跑贯验()
        except Exception as e:  # 写锁竞争失败也要留痕
            战果["贯验异常"] = str(e)

    def 站规线程() -> None:
        就绪.wait()
        try:
            战果["站规"] = 站规.改孤儿覆盖("当前+历史")
        except Exception as e:
            战果["站规异常"] = str(e)

    t1, t2 = threading.Thread(target=贯验线程), threading.Thread(target=站规线程)
    t1.start(); t2.start()
    就绪.set()
    t1.join(timeout=30); t2.join(timeout=30)
    断言(not (t1.is_alive() or t2.is_alive()), "两线程均在时限内结束（写锁串行）")

    conn = 连接()
    try:
        现行 = 孤戳.读覆盖站规(conn)
        证 = 孤戳.核证(conn)
        末次 = 孤戳.末次戳(conn)
        实时历史 = sum(1 for x in __import__(
            "app.modules.贯验孤儿卫星", fromlist=["扫描孤儿"]
        ).扫描孤儿(conn) if not x["是否当前"])
    finally:
        conn.close()
    断言(现行 == "当前+历史", "站规线程最终把口径切到当前+历史")
    断言(实时历史 >= 1, "历史孤儿仍在库中")
    断言(证["有戳"], "必有跑次覆盖戳")
    if 末次["覆盖范围"] == "当前+历史":
        # 贯验在站规变更后拿锁：必须按新范围扫，历史现形、结论失败
        断言(末次["历史孤儿数"] >= 1, "宽范围跑次扫出历史孤儿")
        断言(证["核证通过"] and 战果.get("贯验", {}).get("是否通过") is False, "宽跑次失败且戳互证")
    else:
        # 贯验先拿锁（仅当前）：结论可通过，但戳范围=仅当前与现行分叉，核证失败
        断言(末次["覆盖范围"] == "仅当前", "窄跑次戳诚实钉仅当前")
        断言(not 证["核证通过"] and not 证["可否沿用结论"], "窄戳与现行站规分叉，禁沿用")
        # 分叉态下开版/清扫写闸必须拒绝沿用旧结论
        拒 = 清扫.清扫孤儿()
        断言(拒["结果"] == "拒绝", "分叉态清扫拒绝")
    # 无论谁先谁后，再补一次贯验必按当前+历史扫出历史孤儿
    补 = 贯验.跑贯验()
    断言(补["是否通过"] is False and 补["历史孤儿数"] >= 1, "补跑后历史孤儿不漏网、不标通过")
    断言(贯验行数() == 戳行数(), "并发全程结论与戳 1:1")


def main() -> int:
    print(f"临时库：{临时}")
    try:
        基线_正常夹具()
        场景_当前孤儿()
        场景_仅历史孤儿()
        场景_失败后开版()
        场景_覆盖戳分叉()
        场景_清扫写闸()
        场景_半截回滚()
        场景_并发改站规与贯验()
        print("\n全部自检通过（乙口径当前+历史链；覆盖戳架构「规」：以现行站规为准）。")
        return 0
    except AssertionError as e:
        print(f"\n自检失败：{e}")
        return 1


