"""孤儿扫覆盖戳 · 架构「规」：以现行站规为准。

全局只贯彻这一种口径，分叉规则钉死如下：

1. 每次贯验都是**新跑次**：按跑次开始时的现行站规「孤儿覆盖」确定扫描范围，
   扫描、下结论、钉覆盖戳在同一写事务内同成败——半截失败整票回滚，
   禁止「结论已落而覆盖戳空」。
2. 戳上钉死：跑次号、贯验编号、覆盖范围、孤儿件数摘要、站规版本。
3. 重跑一律按**最新现行站规**重扫并钉新戳；旧戳不可变、仅作审计。
   旧戳范围与现行站规分叉时，只读核证必须判失败且禁止沿用旧结论。
4. 清扫写闸只信覆盖戳：无戳、戳分叉（范围/版本与现行站规不一致）、
   戳结论通过但与实时孤儿对不上，一律拒绝，禁止无戳/分叉清扫改写正式孤儿处置。

对照另一架构「戳」（以跑次覆盖戳为准，本仓不实现）：重跑沿用旧戳范围、
站规变更不得静默扩大已落结论、改范围须显式新开跑次。
两架构在「先仅当前失败 → 站规改当前+历史 → 重跑」上必须可区分：
「规」重跑即按新范围扫出历史孤儿；「戳」重跑沿用仅当前、历史继续漏网。
"""
from __future__ import annotations

import sqlite3

from app.modules.贯验孤儿卫星 import (
    核范围,
    范围当前加历史,
)

架构代号 = "规"
架构说明 = "以现行站规为准：每次贯验新跑次按最新覆盖重扫钉新戳；旧戳分叉即核证失败、禁止沿用"
覆盖站规键 = "孤儿覆盖"
默认覆盖 = 范围当前加历史


# ---------------------------------------------------------------- 站规版本

def 读覆盖站规(conn: sqlite3.Connection) -> str:
    """读现行孤儿覆盖站规；缺省按当前+历史（乙口径基线）。"""
    row = conn.execute("SELECT 值 FROM 站规 WHERE 键=?", (覆盖站规键,)).fetchone()
    值 = row["值"] if row else 默认覆盖
    return 核范围(值)


def 现行站规版本(conn: sqlite3.Connection) -> dict:
    """现行站规版本：取版本表最新一行；版本表为空（极旧库）时按 0 兜底。"""
    row = conn.execute(
        "SELECT 版本号, 孤儿覆盖, 时刻 FROM 站规版本 ORDER BY 版本号 DESC LIMIT 1"
    ).fetchone()
    if row:
        return {"版本号": row["版本号"], "覆盖范围": row["孤儿覆盖"], "时刻": row["时刻"]}
    return {"版本号": 0, "覆盖范围": 读覆盖站规(conn), "时刻": ""}


def 站规版本串(版本: dict) -> str:
    return f"v{版本['版本号']}:{版本['覆盖范围']}"


def 改覆盖站规(conn: sqlite3.Connection, 新范围: str, 来源: str = "站规变更") -> dict:
    """站规覆盖变更：同事务改写站规并开新版本行（版本号自增）。

    调用方必须已持有写事务；本函数不自行提交。
    非法口径拒绝；与现行相同则幂等返回、不开新版本。
    """
    核范围(新范围)
    现 = 读覆盖站规(conn)
    if 新范围 == 现:
        v = 现行站规版本(conn)
        return {"已变更": False, **v}
    from app.seed import 此刻

    conn.execute(
        "INSERT INTO 站规(键, 值) VALUES (?, ?) "
        "ON CONFLICT(键) DO UPDATE SET 值=excluded.值",
        (覆盖站规键, 新范围),
    )
    cur = conn.execute(
        "INSERT INTO 站规版本(孤儿覆盖, 时刻, 来源) VALUES (?,?,?)",
        (新范围, 此刻(), 来源),
    )
    return {"已变更": True, "版本号": cur.lastrowid, "覆盖范围": 新范围, "时刻": 此刻()}


# ---------------------------------------------------------------- 跑次与钉戳

def 新跑次号(conn: sqlite3.Connection) -> str:
    """跑次号顺序自增、确定性：R-0001、R-0002……每跑次贯验一个号。"""
    n = conn.execute("SELECT COUNT(*) AS c FROM 孤儿扫覆盖戳").fetchone()["c"] + 1
    return f"R-{n:04d}"


def _摘要(孤儿: list[dict], 覆盖范围: str) -> str:
    当前 = sum(1 for x in 孤儿 if x["是否当前"])
    历史 = sum(1 for x in 孤儿 if not x["是否当前"])
    头 = f"覆盖{覆盖范围}；孤儿合计{len(孤儿)}（当前{当前}/历史{历史}）"
    if not 孤儿:
        return 头 + "；无死父键"
    样 = "；".join(
        f"{x['卫星类']}#{x['卫星编号']}({'当前' if x['是否当前'] else '历史'})→{x['父哈希'][:18]}"
        for x in 孤儿[:5]
    )
    return 头 + "；样例:" + 样


def 钉覆盖戳(
    conn: sqlite3.Connection,
    跑次号: str,
    贯验编号: int,
    覆盖范围: str,
    孤儿: list[dict],
    版本: dict,
) -> dict:
    """钉跑次覆盖戳。必须在贯验写事务内调用，与结论同成败。

    硬约束：覆盖范围必须是合法口径且与传入站规版本自洽；任何异常向上抛，
    由写事务整票回滚——调用方不得吞异常，杜绝半截戳。
    """
    核范围(覆盖范围)
    版本串 = 站规版本串(版本)
    if 版本["覆盖范围"] != 覆盖范围:
        raise RuntimeError(
            f"钉戳范围与站规版本分叉:戳范围={覆盖范围} 版本={版本串}；禁止带分叉钉戳"
        )
    from app.seed import 此刻

    当前 = sum(1 for x in 孤儿 if x["是否当前"])
    历史 = sum(1 for x in 孤儿 if not x["是否当前"])
    死父 = len({(x["父表"], x["父哈希"]) for x in 孤儿})
    摘要 = _摘要(孤儿, 覆盖范围)
    cur = conn.execute(
        "INSERT INTO 孤儿扫覆盖戳("
        "跑次号, 贯验编号, 覆盖范围, 孤儿件数, 当前孤儿数, 历史孤儿数, 死父键数, "
        "摘要, 站规版本, 时刻"
        ") VALUES (?,?,?,?,?,?,?,?,?,?)",
        (
            跑次号,
            贯验编号,
            覆盖范围,
            len(孤儿),
            当前,
            历史,
            死父,
            摘要,
            版本串,
            此刻(),
        ),
    )
    return {
        "戳编号": cur.lastrowid,
        "跑次号": 跑次号,
        "贯验编号": 贯验编号,
        "覆盖范围": 覆盖范围,
        "孤儿件数": len(孤儿),
        "当前孤儿数": 当前,
        "历史孤儿数": 历史,
        "死父键数": 死父,
        "摘要": 摘要,
        "站规版本": 版本串,
    }


def 列戳(conn: sqlite3.Connection, 限量: int = 50) -> list[dict]:
    return [dict(r) for r in conn.execute(
        "SELECT * FROM 孤儿扫覆盖戳 ORDER BY 编号 DESC LIMIT ?", (限量,)
    )]


def 末次戳(conn: sqlite3.Connection) -> dict | None:
    r = conn.execute("SELECT * FROM 孤儿扫覆盖戳 ORDER BY 编号 DESC LIMIT 1").fetchone()
    return dict(r) if r else None


def 取戳(conn: sqlite3.Connection, 戳编号: int | None = None, 跑次号: str | None = None) -> dict | None:
    if 戳编号 is not None:
        r = conn.execute("SELECT * FROM 孤儿扫覆盖戳 WHERE 编号=?", (戳编号,)).fetchone()
    elif 跑次号 is not None:
        r = conn.execute("SELECT * FROM 孤儿扫覆盖戳 WHERE 跑次号=?", (跑次号,)).fetchone()
    else:
        r = conn.execute("SELECT * FROM 孤儿扫覆盖戳 ORDER BY 编号 DESC LIMIT 1").fetchone()
    return dict(r) if r else None


# ---------------------------------------------------------------- 只读核证

def _戳行核证(戳: dict, 版本: dict, 现行范围: str) -> dict:
    版本串 = 站规版本串(版本)
    分叉项: list[str] = []
    警示: list[str] = []
    # 硬失败：覆盖范围分叉——禁止「当前+历史」口径下沿用仅当前旧结论（反之亦然）
    if 戳["覆盖范围"] != 现行范围:
        分叉项.append(f"戳范围={戳['覆盖范围']} 与现行站规={现行范围} 分叉")
    # 同范围但站规版本号已重切：范围证据仍可采信，仅作警示留痕
    if 戳["站规版本"] != 版本串:
        if 戳["覆盖范围"] == 现行范围:
            警示.append(
                f"戳站规版本={戳['站规版本']} 已重切为现行={版本串}（范围一致，须重跑钉新戳消痕）"
            )
        else:
            分叉项.append(f"戳站规版本={戳['站规版本']} 与现行版本={版本串} 分叉")
    return {
        "戳编号": 戳["编号"],
        "跑次号": 戳["跑次号"],
        "贯验编号": 戳["贯验编号"],
        "覆盖范围": 戳["覆盖范围"],
        "孤儿件数": 戳["孤儿件数"],
        "当前孤儿数": 戳["当前孤儿数"],
        "历史孤儿数": 戳["历史孤儿数"],
        "死父键数": 戳["死父键数"],
        "摘要": 戳["摘要"],
        "站规版本": 戳["站规版本"],
        "时刻": 戳["时刻"],
        "现行站规范围": 现行范围,
        "现行站规版本": 版本串,
        "核证通过": not 分叉项,
        "范围分叉": bool(分叉项),
        "分叉": 分叉项,
        "警示": 警示,
        "可否沿用结论": not 分叉项,
    }


def 核证(
    conn: sqlite3.Connection,
    戳编号: int | None = None,
    跑次号: str | None = None,
) -> dict:
    """孤儿覆盖戳只读核证接口（基线所无，新增）。

    架构「规」的读侧裁决：戳范围/版本与现行站规任一不一致即核证失败，
    且明确「禁止沿用旧结论」。无戳时返回空核证（清扫/开版写闸据此拒绝）。
    """
    版本 = 现行站规版本(conn)
    现行范围 = 读覆盖站规(conn)
    戳 = 取戳(conn, 戳编号, 跑次号)
    if 戳 is None:
        return {
            "架构": 架构代号,
            "架构说明": 架构说明,
            "有戳": False,
            "核证通过": False,
            "可否沿用结论": False,
            "现行站规范围": 现行范围,
            "现行站规版本": 站规版本串(版本),
            "分叉": ["无任何跑次覆盖戳：结论不得采信，写闸必须拒绝"],
            "戳": None,
        }
    证 = _戳行核证(戳, 版本, 现行范围)
    return {"架构": 架构代号, "架构说明": 架构说明, "有戳": True, **证}


def 查戳(conn: sqlite3.Connection) -> dict:
    """覆盖戳履历只读视图（供覆盖戳页面），末次戳附实时核证结论。"""
    版本 = 现行站规版本(conn)
    现行范围 = 读覆盖站规(conn)
    戳列 = 列戳(conn)
    末 = 戳列[0] if 戳列 else None
    末证 = _戳行核证(末, 版本, 现行范围) if 末 else None
    return {
        "架构": 架构代号,
        "架构说明": 架构说明,
        "钉死": True,
        "采信现行": True,
        "现行站规范围": 现行范围,
        "现行站规版本": 站规版本串(版本),
        "末次核证": 末证,
        "覆盖戳": 戳列,
    }


# ---------------------------------------------------------------- 写闸互证

def 清扫写闸(conn: sqlite3.Connection) -> tuple[bool, str, dict | None]:
    """清扫前置闸（只读判定，不改数据）。

    放行三条件，缺一即拒：
    1. 存在跑次覆盖戳（禁止无戳清扫改写正式孤儿处置）；
    2. 戳范围与站规版本和现行站规完全一致（分叉禁止沿用旧结论）；
    3. 戳上孤儿件数与按戳范围实时重扫的孤儿数一致（防戳后数据漂移）。
    """
    证 = 核证(conn)
    if not 证["有戳"]:
        return False, "无跑次覆盖戳：禁止无戳清扫正式孤儿处置", None
    if not 证["核证通过"]:
        return False, "覆盖戳与现行站规分叉：" + "；".join(证["分叉"]), 取戳(conn)
    戳 = 取戳(conn)
    from app.modules.贯验孤儿卫星 import 扫描孤儿

    实时孤儿 = 扫描孤儿(conn, None, 戳["覆盖范围"])
    if len(实时孤儿) != 戳["孤儿件数"]:
        return False, (
            f"戳记孤儿{戳['孤儿件数']}件与实时重扫{len(实时孤儿)}件不符："
            "数据已漂移，须重新贯验钉新戳后再清扫"
        ), 戳
    return True, "覆盖戳与现行站规互证一致，准予按戳范围清扫", 戳


def 开版闸戳互证(conn: sqlite3.Connection) -> tuple[bool, str]:
    """开版/装载写闸的覆盖戳互证环节（与既有实时孤儿闸串联）。

    - 从未贯验（无戳）：不拦，交给实时孤儿闸与父键可解判定；
    - 有戳但与现行站规分叉：拒绝，禁止站规变更后沿用旧结论开新当前；
    - 有戳且互证一致：本环节放行，后续仍须过实时孤儿/死父键闸。
    """
    证 = 核证(conn)
    if not 证["有戳"]:
        return True, "尚无覆盖戳（未贯验），覆盖戳环节不拦"
    if not 证["核证通过"]:
        return False, "覆盖戳与现行站规分叉，禁止沿用旧结论开版：" + "；".join(证["分叉"])
    return True, "覆盖戳与现行站规互证一致"
