"""站规服务：孤儿覆盖口径变更必须开新版本行，供覆盖戳钉版本与核证分叉。"""
from app.db import 连接, 写事务
from app.modules.贯验孤儿卫星 import 合法范围
from app.modules import 孤儿扫覆盖戳 as 孤戳


def 列站规() -> dict:
    conn = 连接()
    try:
        规 = {r["键"]: r["值"] for r in conn.execute("SELECT 键, 值 FROM 站规")}
        版本 = 孤戳.现行站规版本(conn)
        规["_现行版本"] = 孤戳.站规版本串(版本)
        规["_合法孤儿覆盖"] = list(合法范围)
        return 规
    finally:
        conn.close()


def 改孤儿覆盖(新范围: str, 来源: str = "站规页变更") -> dict:
    """改站规覆盖：写事务内改值+开新版本；非法口径/异常整票回滚。

    架构「规」下，变更不抹旧戳——旧戳保留原范围与版本，重跑贯验时只读核证
    会判旧戳与现行分叉、禁止沿用，直到新跑次钉出新戳。
    """
    新范围 = (新范围 or "").strip()
    if 新范围 not in 合法范围:
        return {"结果": "拒绝", "说明": f"非法孤儿覆盖口径:{新范围}，仅支持 {list(合法范围)}"}
    conn = 连接()
    try:
        with 写事务(conn):
            前版本 = 孤戳.现行站规版本(conn)
            变 = 孤戳.改覆盖站规(conn, 新范围, 来源)
            后版本 = 孤戳.现行站规版本(conn)
            # 变更后立即对末次戳做只读核证：把分叉事实显式返回，提示必须重跑贯验
            末证 = 孤戳.核证(conn)
        return {
            "结果": "成功",
            "已变更": 变["已变更"],
            "原范围": 前版本["覆盖范围"],
            "新范围": 后版本["覆盖范围"],
            "现行版本": 孤戳.站规版本串(后版本),
            "末次戳核证": 末证,
            "说明": (
                "站规未变（幂等）"
                if not 变["已变更"]
                else "已开站规新版本；旧覆盖戳即刻分叉，重跑贯验前清扫/开版写闸将拒绝沿用旧结论"
            ),
        }
    except Exception as e:
        return {"结果": "失败", "说明": str(e)}
    finally:
        conn.close()
