"""孤儿清扫服务：无戳/戳分叉/戳实不符一律拒绝；处置与戳互证、同事务同成败。"""
import json

from app.db import 连接, 写事务
from app.modules import 孤儿扫覆盖戳 as 孤戳
from app.modules.贯验孤儿卫星 import 扫描孤儿
from app.seed import 此刻

# 半截故障注入：置 True 后，下一次清扫在「隔离匣已写、处置单未钉」窗口抛错，
# 自检验证整票回滚——正式孤儿处置禁止半截落库。
故障_清扫中炸 = False


def 清扫孤儿() -> dict:
    conn = 连接()
    try:
        with 写事务(conn):
            放行, 因, 戳 = 孤戳.清扫写闸(conn)
            if not 放行:
                return {"结果": "拒绝", "说明": 因, "增量": {"处置": 0}, "闸": "失败闭"}

            # 事务内再按戳范围实时取一遍孤儿，处置对象以实时结果为准、件数与戳互证
            孤儿 = 扫描孤儿(conn, None, 戳["覆盖范围"])
            if len(孤儿) != 戳["孤儿件数"]:
                return {
                    "结果": "拒绝",
                    "说明": f"戳记{戳['孤儿件数']}件与实时{len(孤儿)}件不符，拒绝清扫",
                    "增量": {"处置": 0},
                    "闸": "失败闭",
                }
            if not 孤儿:
                # 幂等空扫：闸已互证、库内无孤儿，不写正式处置单
                return {
                    "结果": "成功",
                    "说明": f"戳{戳['跑次号']}互证一致且库内无孤儿，空扫幂等、不增处置单",
                    "跑次号": 戳["跑次号"],
                    "覆盖戳编号": 戳["编号"],
                    "站规版本": 戳["站规版本"],
                    "覆盖范围": 戳["覆盖范围"],
                    "处置数": 0,
                    "增量": {"处置": 0},
                    "闸": "通行",
                }

            隔离编号: list[int] = []
            for x in 孤儿:
                cur = conn.execute(
                    "INSERT INTO 隔离匣(原因, 载荷, 时刻) VALUES (?,?,?)",
                    (
                        f"孤儿清扫/{戳['跑次号']}/{x['卫星表']}#{x['卫星编号']}父不可解",
                        json.dumps(x, ensure_ascii=False),
                        此刻(),
                    ),
                )
                隔离编号.append(cur.lastrowid)
                conn.execute(
                    f"DELETE FROM {x['卫星表']} WHERE 编号=?", (x["卫星编号"],)
                )

            # 半截故障注入点：隔离与删除已发生、处置单未钉。异常必须整票回滚。
            global 故障_清扫中炸
            if 故障_清扫中炸:
                故障_清扫中炸 = False
                raise RuntimeError("故障注入：孤儿处置单钉死前中断（验证整票回滚）")

            处置 = conn.execute(
                "INSERT INTO 孤儿处置("
                "时刻, 跑次号, 覆盖戳编号, 贯验编号, 站规版本, 覆盖范围, 处置数, "
                "隔离匣编号, 摘要, 结果"
                ") VALUES (?,?,?,?,?,?,?,?,?,?)",
                (
                    此刻(),
                    戳["跑次号"],
                    戳["编号"],
                    戳["贯验编号"],
                    戳["站规版本"],
                    戳["覆盖范围"],
                    len(孤儿),
                    隔离编号[0] if 隔离编号 else 0,
                    戳["摘要"],
                    "成功",
                ),
            )
            return {
                "结果": "成功",
                "说明": f"按戳{戳['跑次号']}（{戳['覆盖范围']}）清扫孤儿 {len(孤儿)} 件，已入隔离匣",
                "处置编号": 处置.lastrowid,
                "跑次号": 戳["跑次号"],
                "覆盖戳编号": 戳["编号"],
                "站规版本": 戳["站规版本"],
                "覆盖范围": 戳["覆盖范围"],
                "处置数": len(孤儿),
                "增量": {"处置": len(孤儿)},
                "闸": "通行",
            }
    except Exception as e:
        return {"结果": "失败", "说明": str(e), "增量": {"处置": 0}, "闸": "失败闭"}
    finally:
        conn.close()


def 列处置(限量: int = 50) -> list[dict]:
    conn = 连接()
    try:
        return [dict(r) for r in conn.execute(
            "SELECT * FROM 孤儿处置 ORDER BY 编号 DESC LIMIT ?", (限量,)
        )]
    finally:
        conn.close()
